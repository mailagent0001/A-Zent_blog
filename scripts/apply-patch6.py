p = 'src/pages/privacy.astro'
s = open(p, encoding='utf-8').read()
if '請求書・領収書サービスに関する個人情報の取扱い' in s:
    print('すでに適用済みです'); raise SystemExit
anchor = '</div></div>\n</HpLayout>'
assert s.count(anchor) == 1, '末尾の目印が見つかりません(ファイルの形が想定と違います)'
H3 = '<h3 style="font-size:1.05rem;margin:28px 0 8px">'
OL = '<ol style="list-style:decimal;padding-left:1.4em;margin:8px 0">'
new = (
 '<h2 id="invoice-service">請求書・領収書サービスに関する個人情報の取扱い</h2>'
 '<p>アゼント(以下「当社」)は、当社が提供する請求書・領収書の経理サービス(以下「本サービス」)における、個人情報の取扱いについて、次のとおり定めます。</p>'
 + H3 + '取得する情報</h3><ul>'
 '<li>利用者(会社)の登録情報。</li>'
 '<li>利用者が入力・アップロードした請求書・領収書等に記載された取引先の情報(会社名、所在地、電話番号、担当者名、メールアドレス等)。</li>'
 '<li>ログインに使うメールアドレス、規約への同意の日時と版。</li>'
 '<li>Googleでログインした場合に、Googleから受け取るメールアドレス(ログインの本人確認に使用します)。</li></ul>'
 + H3 + '利用目的</h3>' + OL +
 '<li>本サービスの提供、運営、本人確認。</li>'
 '<li>取引先への本サービス導入の周知および入力依頼の代行。</li>'
 '<li>領収書の画像からの文字の読み取り(外部のAI事業者(米国)へ画像を送信します。送信先では、不正利用の監視のために一定期間保存されることがありますが、学習には利用されません)。</li>'
 '<li>問合せへの対応、障害対応、規約変更等の通知。</li></ol>'
 + H3 + '案内の方法と停止</h3><ul>'
 '<li>案内を希望しない場合は、info@a-zent.com にご連絡ください。以後、案内を停止いたします。</li></ul>'
 + H3 + '保存期間</h3><ul>'
 '<li>領収書の画像: アップロードから90日で自動削除します。読み取った項目の記録は削除しません。</li>'
 '<li>退会後: 90日以内にデータを削除します(退会前のダウンロードをご案内します)。</li>'
 '<li>取引先の情報(周知・案内用): 退会後90日以内に削除します。</li>'
 '<li>規約への同意の記録: サービスの提供期間中、および退会後90日以内に削除します。</li></ul>'
 + H3 + '外国にある第三者への提供</h3><ul>'
 '<li>領収書の画像の読み取りのため、外部のAI事業者(米国)に画像を送信します。</li>'
 '<li>Googleでログインした場合、本人確認のため、Google(米国)と通信します。</li>'
 '<li>システムの運用のため、外部のクラウド事業者のサービスを利用します。</li></ul>'
 + H3 + 'ご連絡先</h3><p>info@a-zent.com</p>'
)
s = s.replace(anchor, new + anchor, 1)
# ページのタイトルと説明が、トップページと同じになっていたので、このページ用にする
t = 'const title = "沖縄のIT導入・DX支援・業務自動化|A-Zent(アゼント)";'
if t in s:
    s = s.replace(t, 'const title = "プライバシーポリシー|A-Zent";', 1)
    s = re.sub(r'const description = ".*?";', 'const description = "A-Zentの個人情報の取扱いについて(ウェブサイト、および請求書・領収書サービス)。";', s, count=1)
    print('タイトルと説明を、このページ用に変更しました')
open(p, 'w', encoding='utf-8').write(s)
print('追記しました')
